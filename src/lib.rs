fn manifest() -> Value {
    json!({
        "name": "themes",
        "version": env!("CARGO_PKG_VERSION"),
        "protocol": "1.1",
        "tools": [],
        "commands": ["/theme", "/palettes"],
        "turn_local": {"/theme": ["*"], "/palettes": ["*"]},
        "hooks": [],
        "capabilities": ["host.restart"],
        "completion": ["list", "use", "install", "show", "path", "new"],
    })
}

pub(crate) fn gray_home() -> PathBuf {
    std::env::var_os("GRAY_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".gray")))
        .unwrap_or_else(|| PathBuf::from("."))
}

pub(crate) fn themes_dir() -> PathBuf {
    gray_home().join("themes")
}

/// The persisted theme choice — `config.json`'s `"theme"` field, which is
/// what `/theme <name>` writes and startup reads.
pub(crate) fn saved_theme() -> Option<String> {
    let text = std::fs::read_to_string(gray_home().join("config.json")).ok()?;
    serde_json::from_str::<Value>(&text).ok()?["theme"]
        .as_str()
        .map(str::to_string)
}

/// Persist a theme name into `config.json` (CLI `use` only — the sidecar
/// leaves persistence to `/theme` so a running TUI stays the writer).
pub(crate) fn persist_theme(name: Option<&str>) -> Result<(), String> {
    let path = gray_home().join("config.json");
    let mut doc: Value = std::fs::read_to_string(&path)
        .ok()
        .and_then(|t| serde_json::from_str(&t).ok())
        .unwrap_or_else(|| json!({}));
    if !doc.is_object() {
        doc = json!({});
    }
    match name {
        Some(n) => doc["theme"] = json!(n),
        None => {
            if let Some(o) = doc.as_object_mut() {
                o.remove("theme");
            }
        }
    }
    let text = serde_json::to_string_pretty(&doc).map_err(|e| e.to_string())?;
    std::fs::write(&path, text + "\n").map_err(|e| format!("{}: {e}", path.display()))
}

/// `"saga"` names the theme; a legacy `"hancore-saga"` resolves too.
pub(crate) fn find(name: &str) -> Option<&'static (&'static str, &'static str)> {
    let bare = name.strip_prefix("hancore-").unwrap_or(name);
    THEMES.iter().find(|(n, _)| *n == bare)
}

pub(crate) fn installed(name: &str) -> bool {
    themes_dir().join(format!("{name}.json")).is_file()
}

/// Pack files carry our `_source` marker; never overwrite a theme file
/// that doesn't (it belongs to the user, not to this pack).
fn install(entry: &(&str, &str)) -> Result<(), String> {
    let dir = themes_dir();
    std::fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    let path = dir.join(format!("{}.json", entry.0));
    if let Ok(existing) = std::fs::read_to_string(&path)
        && !existing.contains("\"_source\"")
    {
        return Err(format!(
            "{} exists and isn't from this pack — left alone",
            path.display()
        ));
    }
    std::fs::write(&path, entry.1).map_err(|e| format!("{}: {e}", path.display()))
}

fn meta(entry: &(&str, &str)) -> Value {
    serde_json::from_str(entry.1).unwrap_or(Value::Null)
}

fn list() -> String {
    let active = saved_theme();
    let mut out = format!("themes — {} palettes\n", THEMES.len());
    for entry in THEMES {
        let m = meta(entry);
        let mode = m["_mode"].as_str().unwrap_or("?");
        let v = &m["vars"];
        let bg = v["bg"].as_str().unwrap_or("?");
        let fg = v["fg"].as_str().unwrap_or("?");
        let accent = v["accent"].as_str().unwrap_or("?");
        let mark = if active.as_deref() == Some(entry.0) {
            "●"
        } else if installed(entry.0) {
            "✓"
        } else {
            " "
        };
        out.push_str(&format!(
            "  {mark} {:<14} {mode:<5} bg {bg} fg {fg} accent {accent}\n",
            entry.0
        ));
    }
    out.push_str("● active · ✓ installed · /palettes use <name> then /theme <name> to switch");
    out
}

fn show(entry: &(&str, &str)) -> String {
    let m = meta(entry);
    let src = m["_source"].as_str().unwrap_or("");
    let mode = m["_mode"].as_str().unwrap_or("?");
    let mut out = format!("{} — {mode}\n{src}\n", entry.0);
    if let Some(vars) = m["vars"].as_object() {
        for (k, v) in vars {
            out.push_str(&format!("  {k:<9} {}\n", v.as_str().unwrap_or("?")));
        }
    }
    out
}

const USAGE: &str = "usage: palettes [list | use <name> | install [name|all] | show <name> | path]
  list             all 32 palettes (● active, ✓ installed)
  use <name>       install + select it (CLI also writes config.json)
  install [name]   write theme file(s) into ~/.gray/themes
  show <name>      dump a palette
  path             the themes dir";

fn run_cmd(argv: &[String], persist: bool) -> String {
    match argv.first().map(String::as_str) {
        None | Some("list") => list(),
        Some("path") => themes_dir().display().to_string(),
        Some("show") => match argv.get(1).and_then(|n| find(n)) {
            Some(entry) => show(entry),
            None => format!("no such theme `{}` — /palettes list", argv.get(1).map_or("", String::as_str)),
        },
        Some("install") => match argv.get(1).map(String::as_str) {
            None | Some("all") => {
                let mut errs = Vec::new();
                let mut n = 0;
                for entry in THEMES {
                    match install(entry) {
                        Ok(()) => n += 1,
                        Err(e) => errs.push(e),
                    }
                }
                if errs.is_empty() {
                    format!("✓ installed {n} themes → {}", themes_dir().display())
                } else {
                    format!("installed {n}, skipped {}:\n{}", errs.len(), errs.join("\n"))
                }
            }
            Some(name) => match find(name) {
                Some(entry) => match install(entry) {
                    Ok(()) => format!("✓ installed {} → {}", entry.0, themes_dir().display()),
                    Err(e) => format!("install skipped: {e}"),
                },
                None => format!("no such theme `{name}` — /palettes list"),
            },
        },
        Some("use") => {
            let Some(name) = argv.get(1) else {
                return "usage: palettes use <name>".into();
            };
            match find(name) {
                Some(entry) => match install(entry) {
                    Ok(()) => {
                        let mut msg = format!("✓ installed {}", entry.0);
                        if persist {
                            match persist_theme(Some(entry.0)) {
                                Ok(()) => msg.push_str(" + set in config.json (next launch)"),
                                Err(e) => msg.push_str(&format!(" (config not saved: {e})")),
                            }
                        }
                        msg.push_str(&format!(" — /theme {} switches a live TUI", entry.0));
                        msg
                    }
                    Err(e) => format!("install skipped: {e}"),
                },
                None => format!("no such theme `{name}` — /palettes list"),
            }
        }
        _ => USAGE.into(),
    }
}

/// `/theme` surface: bare hands the terminal to the picker; `list`/`new`/`<name>`
/// answer inline. Applies request a host restart (config is written first).
fn theme_run(argv: &[String]) -> (Value, bool) {
    let arg = argv.first().map(String::as_str).unwrap_or("");
    match arg.split_whitespace().collect::<Vec<_>>().as_slice() {
        [] => (json!({ "terminal": ["theme"], "text": "opening the theme picker…" }), false),
        ["list"] => {
            let active = saved_theme();
            let mut out = format!("themes — ~/.gray/themes + {} pack palettes\n", THEMES.len());
            for r in picker::rows() {
                let mark = if active.as_deref() == Some(r.name.as_str())
                    || (active.is_none() && r.builtin) { "●" } else { " " };
                let tag = if r.builtin { " (built-in)" }
                    else if !r.installed { " — pack, installs on apply" } else { "" };
                out.push_str(&format!("  {mark} {}{tag}\n", r.name));
            }
            out.push_str("/theme <name> to switch · /theme new <name> to copy the saved one");
            (json!({ "text": out }), false)
        }
        ["new", name] => {
            if name.is_empty() || !name.chars().all(|c| c.is_ascii_alphanumeric() || "-_".contains(c))
                || *name == "gray" || name.eq_ignore_ascii_case("default") {
                return (json!({ "text": format!("`{name}` can't be a theme name") }), false);
            }
            let path = themes_dir().join(format!("{name}.json"));
            if path.exists() {
                return (json!({ "text": format!("{} already exists", path.display()) }), false);
            }
            let src = saved_theme()
                .and_then(|t| std::fs::read_to_string(themes_dir().join(format!("{t}.json"))).ok())
                .or_else(|| find("saga").map(|e| e.1.to_string()))
                .unwrap_or_else(|| THEMES[0].1.to_string());
            match std::fs::create_dir_all(themes_dir())
                .and_then(|()| std::fs::write(&path, src)) {
                Ok(()) => (json!({ "text": format!("wrote {} — edit it, then /theme {name}", path.display()) }), false),
                Err(e) => (json!({ "text": format!("could not write {}: {e}", path.display()) }), false),
            }
        }
        ["reload", ..] => (json!({ "text": "theme files are read from disk on apply — /theme <name> re-applies" }), false),
        [name] => {
            let msg = picker::apply(name);
            (json!({ "text": msg }), msg.starts_with("theme "))
        }
        _ => (json!({ "text": "usage: /theme [<name> | new <name> | list]" }), false),
    }
}

fn handle(req: &Value) -> (Option<Value>, bool) {
    let id = req.get("id").cloned();
    let method = req.get("method").and_then(Value::as_str).unwrap_or("");
    let params = req.get("params").cloned().unwrap_or(Value::Null);
    let Some(id) = id else {
        return (None, method == "plugin/shutdown");
    };
    let result = match method {
        "plugin/manifest" => manifest(),
        "command/run" => {
            let argv: Vec<String> = params
                .get("argv")
                .and_then(Value::as_array)
                .map(|a| a.iter().filter_map(|e| e.as_str().map(str::to_string)).collect())
                .unwrap_or_default();
            let name = params.get("name").and_then(Value::as_str).unwrap_or("");
            if name == "/theme" {
                let (mut v, restart) = theme_run(&argv);
                if restart {
                    v["then_restart"] = json!(true);
                }
                v
            } else {
                json!({ "text": run_cmd(&argv, false) })
            }
        }
        "plugin/shutdown" => return (Some(json!({ "id": id, "result": {} })), true),
        _ => {
            return (
                Some(json!({ "id": id, "error": { "code": -32601, "message": format!("method not found: {method}") } })),
                false,
            );
        }
    };
    (Some(json!({ "id": id, "result": result })), false)
}

/// Ask the host to restart gray (applies the just-saved theme). Reads replies
/// until our id answers, bounded, then returns — the host tears us down on a
/// granted restart anyway.
fn host_restart(stdin: &std::io::Stdin, stdout: &mut std::io::Stdout) {
    let _ = writeln!(
        stdout,
        "{}",
        json!({"id": "themes-restart", "method": "host/restart", "params": {"resume": true}})
    );
    let _ = stdout.flush();
    for _ in 0..30 {
        let mut line = String::new();
        if stdin.lock().read_line(&mut line).is_err() || line.is_empty() {
            break;
        }
        if let Ok(v) = serde_json::from_str::<Value>(&line)
            && v.get("id").and_then(Value::as_str) == Some("themes-restart")
        {
            break;
        }
    }
}

/// Entry: `manifest` prints; bare-on-a-pipe serves the wire; anything else
/// is the `gray themes …` CLI surface.
pub fn run() -> std::io::Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.first().map(String::as_str) == Some("manifest") {
        println!("{}", manifest());
        return Ok(());
    }
    if args.is_empty() {
        if std::io::stdin().is_terminal() {
            eprintln!("gray-themes is a plugin sidecar — drive it via `gray themes …` or install with `gray plugin install`");
            return Ok(());
        }
        let stdin = std::io::stdin();
        let mut stdout = std::io::stdout();
        for line in stdin.lock().lines() {
            let line = line?;
            let Ok(req) = serde_json::from_str::<Value>(&line) else {
                continue;
            };
            let (reply, exit) = handle(&req);
            let mut restart = false;
            if let Some(mut reply) = reply {
                if reply.pointer("/result/then_restart").is_some() {
                    restart = true;
                    if let Some(r) = reply.pointer_mut("/result").and_then(Value::as_object_mut) {
                        r.remove("then_restart");
                    }
                }
                writeln!(stdout, "{reply}")?;
                stdout.flush()?;
            }
            if restart {
                host_restart(&stdin, &mut stdout);
            }
            if exit {
                break;
            }
        }
        return Ok(());
    }
    match args.first().map(String::as_str) {
        Some("theme") => {
            if let Some(name) = picker::pick() {
                println!("{}", picker::apply(&name));
            } else {
                println!("theme picker closed");
            }
        }
        Some("help") | Some("--help") | Some("-h") => println!("{USAGE}"),
        _ => println!("{}", run_cmd(&args, true)),
    }
    Ok(())
}
