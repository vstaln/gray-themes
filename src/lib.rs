fn manifest() -> Value {
    json!({
        "name": "themes",
        "version": env!("CARGO_PKG_VERSION"),
        "protocol": "1.1",
        "tools": [],
        "commands": ["/themes"],
        "hooks": [],
        "completion": ["list", "use", "install", "show", "path"],
    })
}

fn gray_home() -> PathBuf {
    std::env::var_os("GRAY_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".gray")))
        .unwrap_or_else(|| PathBuf::from("."))
}

fn themes_dir() -> PathBuf {
    gray_home().join("themes")
}

/// The persisted theme choice — `config.json`'s `"theme"` field, which is
/// what `/theme <name>` writes and startup reads.
fn saved_theme() -> Option<String> {
    let text = std::fs::read_to_string(gray_home().join("config.json")).ok()?;
    serde_json::from_str::<Value>(&text).ok()?["theme"]
        .as_str()
        .map(str::to_string)
}

/// Persist a theme name into `config.json` (CLI `use` only — the sidecar
/// leaves persistence to `/theme` so a running TUI stays the writer).
fn persist_theme(name: &str) -> Result<(), String> {
    let path = gray_home().join("config.json");
    let mut doc: Value = std::fs::read_to_string(&path)
        .ok()
        .and_then(|t| serde_json::from_str(&t).ok())
        .unwrap_or_else(|| json!({}));
    if !doc.is_object() {
        doc = json!({});
    }
    doc["theme"] = json!(name);
    let text = serde_json::to_string_pretty(&doc).map_err(|e| e.to_string())?;
    std::fs::write(&path, text + "\n").map_err(|e| format!("{}: {e}", path.display()))
}

/// `"saga"` and `"hancore-saga"` both name the same theme.
fn find(name: &str) -> Option<&'static (&'static str, &'static str)> {
    let bare = name.strip_prefix("hancore-").unwrap_or(name);
    THEMES
        .iter()
        .find(|(n, _)| *n == name || n.strip_prefix("hancore-") == Some(bare))
}

fn installed(name: &str) -> bool {
    themes_dir().join(format!("{name}.json")).is_file()
}

fn install(entry: &(&str, &str)) -> Result<(), String> {
    let dir = themes_dir();
    std::fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    let path = dir.join(format!("{}.json", entry.0));
    std::fs::write(&path, entry.1).map_err(|e| format!("{}: {e}", path.display()))
}

fn meta(entry: &(&str, &str)) -> Value {
    serde_json::from_str(entry.1).unwrap_or(Value::Null)
}

fn list() -> String {
    let active = saved_theme();
    let mut out = format!(
        "hancore themes — {} palettes · github.com/HANCORE-linux\n",
        THEMES.len()
    );
    for entry in THEMES {
        let m = meta(entry);
        let mode = m["_mode"].as_str().unwrap_or("?");
        let v = &m["vars"];
        let bg = v["bg"].as_str().unwrap_or("?");
        let fg = v["fg"].as_str().unwrap_or("?");
        let accent = v["accent"].as_str().unwrap_or("?");
        let mark = if active.as_deref() == Some(entry.0) {
            "●"
        } else if installed(entry.0) {
            "✓"
        } else {
            " "
        };
        out.push_str(&format!(
            "  {mark} {:<22} {mode:<5} bg {bg} fg {fg} accent {accent}\n",
            entry.0
        ));
    }
    out.push_str(
        "● active · ✓ installed · /themes use <name> then /theme <name> to switch",
    );
    out
}

fn show(entry: &(&str, &str)) -> String {
    let m = meta(entry);
    let src = m["_source"].as_str().unwrap_or("");
    let mode = m["_mode"].as_str().unwrap_or("?");
    let mut out = format!("{} — {mode}\n{src}\n", entry.0);
    if let Some(vars) = m["vars"].as_object() {
        for (k, v) in vars {
            out.push_str(&format!("  {k:<9} {}\n", v.as_str().unwrap_or("?")));
        }
    }
    out
}

const USAGE: &str = "usage: themes [list | use <name> | install [name|all] | show <name> | path]
  list             all 29 hancore palettes (● active, ✓ installed)
  use <name>       install + select it (CLI also writes config.json)
  install [name]   write theme file(s) into ~/.gray/themes
  show <name>      dump a palette
  path             the themes dir";

fn run_cmd(argv: &[String], persist: bool) -> String {
    match argv.first().map(String::as_str) {
        None | Some("list") => list(),
        Some("path") => themes_dir().display().to_string(),
        Some("show") => match argv.get(1).and_then(|n| find(n)) {
            Some(entry) => show(entry),
            None => format!("no such theme `{}` — /themes list", argv.get(1).map_or("", String::as_str)),
        },
        Some("install") => match argv.get(1).map(String::as_str) {
            None | Some("all") => {
                let mut errs = Vec::new();
                for entry in THEMES {
                    if let Err(e) = install(entry) {
                        errs.push(e);
                    }
                }
                if errs.is_empty() {
                    format!("✓ installed {} themes → {}", THEMES.len(), themes_dir().display())
                } else {
                    format!("installed with errors:\n{}", errs.join("\n"))
                }
            }
            Some(name) => match find(name) {
                Some(entry) => match install(entry) {
                    Ok(()) => format!("✓ installed {} → {}", entry.0, themes_dir().display()),
                    Err(e) => format!("install failed: {e}"),
                },
                None => format!("no such theme `{name}` — /themes list"),
            },
        },
        Some("use") => {
            let Some(name) = argv.get(1) else {
                return "usage: themes use <name>".into();
            };
            match find(name) {
                Some(entry) => match install(entry) {
                    Ok(()) => {
                        let mut msg = format!("✓ installed {}", entry.0);
                        if persist {
                            match persist_theme(entry.0) {
                                Ok(()) => msg.push_str(" + set in config.json (next launch)"),
                                Err(e) => msg.push_str(&format!(" (config not saved: {e})")),
                            }
                        }
                        msg.push_str(&format!(" — /theme {} switches a live TUI", entry.0));
                        msg
                    }
                    Err(e) => format!("install failed: {e}"),
                },
                None => format!("no such theme `{name}` — /themes list"),
            }
        }
        _ => USAGE.into(),
    }
}

fn handle(req: &Value) -> (Option<Value>, bool) {
    let id = req.get("id").cloned();
    let method = req.get("method").and_then(Value::as_str).unwrap_or("");
    let params = req.get("params").cloned().unwrap_or(Value::Null);
    let Some(id) = id else {
        return (None, method == "plugin/shutdown");
    };
    let result = match method {
        "plugin/manifest" => manifest(),
        "command/run" => {
            let argv: Vec<String> = params
                .get("argv")
                .and_then(Value::as_array)
                .map(|a| a.iter().filter_map(|e| e.as_str().map(str::to_string)).collect())
                .unwrap_or_default();
            json!({ "text": run_cmd(&argv, false) })
        }
        "plugin/shutdown" => return (Some(json!({ "id": id, "result": {} })), true),
        _ => {
            return (
                Some(json!({ "id": id, "error": { "code": -32601, "message": format!("method not found: {method}") } })),
                false,
            );
        }
    };
    (Some(json!({ "id": id, "result": result })), false)
}

/// Entry: `manifest` prints; bare-on-a-pipe serves the wire; anything else
/// is the `gray themes …` CLI surface.
pub fn run() -> std::io::Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.first().map(String::as_str) == Some("manifest") {
        println!("{}", manifest());
        return Ok(());
    }
    if args.is_empty() {
        if std::io::stdin().is_terminal() {
            eprintln!("gray-themes is a plugin sidecar — drive it via `gray themes …` or install with `gray plugin install`");
            return Ok(());
        }
        let stdin = std::io::stdin();
        let mut stdout = std::io::stdout();
        for line in stdin.lock().lines() {
            let line = line?;
            let Ok(req) = serde_json::from_str::<Value>(&line) else {
                continue;
            };
            let (reply, exit) = handle(&req);
            if let Some(reply) = reply {
                writeln!(stdout, "{reply}")?;
                stdout.flush()?;
            }
            if exit {
                break;
            }
        }
        return Ok(());
    }
    match args.first().map(String::as_str) {
        Some("help") | Some("--help") | Some("-h") => println!("{USAGE}"),
        _ => println!("{}", run_cmd(&args, true)),
    }
    Ok(())
}
