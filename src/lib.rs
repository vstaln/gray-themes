//! gray-themes — a 32-palette theme pack for gray.
//!
//! Ships palettes converted from upstream `colors.toml` files (provenance
//! in each file's `_source`) as embedded gray theme files. Installing one
//! is just writing `~/.gray/themes/<name>.json`; the built-in `/theme`
//! command does the live switch (a sidecar can't flip the palette —
//! `/theme` is TUI-local), so `use` answers with the command to run.
//!
//! - `gray-themes manifest` → manifest JSON (install probe)
//! - `gray themes <verb>` → CLI surface via the host's `cli_argv` forward:
//!   `list`, `use <name>` (install + set `"theme"` in config.json),
//!   `install [name|all]`, `show <name>`, `path`
//! - bare on a pipe → NDJSON sidecar: `command/run` carries `/palettes …`
//!   (`/themes` would collide with the built-in `/theme` alias)
//!
//! Regenerate `themes/` from upstream with `scripts/sync.py`.

